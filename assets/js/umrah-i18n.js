  var RTL = { ur: true };

  /* Collect every translatable node once and remember its English markup. */
  var nodes = [];
  function add(el, getter) {
    if (!el) return;
    el.setAttribute('data-en', el.innerHTML);
    nodes.push({ el: el, get: getter });
  }

  add(root.querySelector('.section-head .eyebrow'), function (t) { return t.head.eyebrow; });
  add(root.querySelector('.section-head .section-title'), function (t) { return t.head.title; });
  add(root.querySelector('.section-head .section-lead'), function (t) { return t.head.lead; });

  ['ihram', 'tawaf', 'sai', 'halq'].forEach(function (id) {
    var art = document.getElementById(id);
    if (!art) return;
    add(art.querySelector('.rite-num .lbl'), function (t) { return t.step; });
    add(art.querySelector('.rite-num .nm'), function (t) { return t.rites[id].nm; });
    add(art.querySelector('h3'), function (t) { return t.rites[id].h3; });
    add(art.querySelector('.lead-p'), function (t) { return t.rites[id].lead; });
    art.querySelectorAll('.steps-list > li').forEach(function (li, i) {
      add(li, function (t) { return t.rites[id].li[i]; });
    });
    add(art.querySelector('.tip > div'), function (t) { return t.rites[id].tip; });
  });

  var textCols = root.querySelectorAll('.rite .col-lg-7');
  var headEls = root.querySelectorAll('.section-head > *:not(.lang-switch)');
  var restNums = root.querySelectorAll('.rite-num .lbl, .rite-num .nm');

  function setDir(list, lang) {
    list.forEach(function (el) {
      if (lang === 'en') { el.removeAttribute('lang'); el.removeAttribute('dir'); }
      else { el.setAttribute('lang', lang); el.setAttribute('dir', RTL[lang] ? 'rtl' : 'ltr'); }
    });
  }

  function apply(lang) {
    var t = T[lang];
    nodes.forEach(function (n) {
      var html = (lang === 'en' || !t) ? n.el.getAttribute('data-en') : n.get(t);
      if (html != null) n.el.innerHTML = html;
    });
    setDir(textCols, lang);
    setDir(headEls, lang);
    setDir(restNums, lang);
    root.setAttribute('data-lang', lang);
    root.classList.remove('is-switching');
  }

  var current = 'en';
  buttons.forEach(function (btn) {
    btn.addEventListener('click', function () {
      var lang = btn.getAttribute('data-lang');
      if (lang === current) return;
      current = lang;
      buttons.forEach(function (b) {
        var on = b === btn;
        b.classList.toggle('is-active', on);
        b.setAttribute('aria-pressed', on ? 'true' : 'false');
      });
      root.classList.add('is-switching');
      setTimeout(function () { apply(lang); }, 180);
    });
  });
